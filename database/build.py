"""Build the local SQL/ERD/dictionary from the checked-in Notion snapshot.

No network access and no database mutations. Run from any directory.
"""
from pathlib import Path
import re
import json

ROOT = Path(__file__).resolve().parent
SOURCE = ROOT / 'source/notion-2026-10-15.sql'
MODULES = {
    'A-identity': 'users oauth_identities student_profiles user_preferences admin_accounts devices device_change_requests auth_sessions security_events',
    'B-academic': 'departments academic_years terms student_term_enrollments department_subjects exam_schedules',
    'C-content': 'learning_containers subjects course_categories courses course_outcomes lessons video_assets video_renditions video_subtitles pdf_documents pdf_versions container_pdfs lesson_pdfs content_contributors pdf_contributors',
    'D-exercises': 'exercises mcq_options code_exercise_specs exercise_attempts attempt_mcq_choices code_submissions ai_evaluations ai_evaluation_findings',
    'E-offline': 'lesson_watch_progress lesson_ratings usage_sessions video_license_requests offline_video_downloads offline_pdf_downloads device_time_syncs protected_pdf_licenses',
    'F-commerce': 'products product_prices product_subject_term product_semester_bundle product_course payments payment_shamcash payment_manual_receipts payment_admin_grants voucher_outlets voucher_batches vouchers entitlements product_bundle_subjects',
    'G-grades': 'grade_import_batches grade_import_rows transcript_submissions grades grade_report_exports grading_schemes grade_revisions',
    'H-communication': 'announcements announcement_attachments notification_templates notifications notification_recipients support_conversations support_messages support_message_attachments',
    'I-system': 'files admin_audit_logs feature_flags app_settings app_versions',
}


def build():
    source = SOURCE.read_text()
    # Each replacement must match exactly once: source drift must be reviewed.
    replacements = {
        "('DOWNLOADABLE', 'VIEW_ONLY')": "('DOWNLOADABLE', 'VIEW_ONLY', 'ENCRYPTED_IN_APP')",
        'CHECK (study_year BETWEEN 1 AND 3)': 'CHECK (study_year BETWEEN 1 AND 2)',
        "pdf_download_policy pdf_download_policy NOT NULL DEFAULT 'DOWNLOADABLE'": 'pdf_download_policy pdf_download_policy NOT NULL',
        '  practical_weight smallint NOT NULL,\n  theoretical_weight smallint NOT NULL,\n  pass_mark smallint NOT NULL DEFAULT 60,\n': '',
        "  CHECK (kind = 'SUBJECT'),\n  CHECK (practical_weight + theoretical_weight = 100)": "  CHECK (kind = 'SUBJECT')",
        '  is_free_preview boolean NOT NULL DEFAULT false,\n': '',
        '  is_free boolean NOT NULL DEFAULT true,': '  is_free boolean NOT NULL,',
        "  currency char(3) NOT NULL DEFAULT 'SYP',": '  currency char(3) NOT NULL,',
        '  total_mark numeric(5,2) GENERATED ALWAYS AS (practical_mark + theoretical_mark) STORED,': '  total_mark numeric(5,2), -- Set by validate_grade(), using an immutable grading scheme.',
    }
    for old, new in replacements.items():
        if source.count(old) != 1:
            raise ValueError(f'Source drift: expected one occurrence of {old!r}')
        source = source.replace(old, new)
    header = ('-- GENERATED by python3 database/build.py. Edit source or amendments.sql, not this file.\n'
              '-- Fresh empty database only. Local design draft; no deployment or production data.\n'
              '-- Notion source + reviewed changes of 2026-10-15. See README.md for policy blockers.\n'
              'BEGIN;\n\n')
    sql = header + source + '\n\n' + (ROOT / 'amendments.sql').read_text() + '\nCOMMIT;\n'
    (ROOT / 'schema.sql').write_text(sql)

    tables = dict(re.findall(r'CREATE TABLE (\w+)\s*\((.*?)\n\);', sql, re.S))
    for name, definition in re.findall(r'ALTER TABLE (\w+)\s+ADD COLUMN (.*?)(?=,\s+ADD CONSTRAINT|;)', sql, re.S):
        tables[name] = tables[name].rstrip().rstrip(',') + ',\n  ' + definition.strip()
    tables['department_subjects'] = tables['department_subjects'].replace(
        'PRIMARY KEY (department_id, subject_id)',
        'PRIMARY KEY (department_id, subject_id, study_year, semester_in_year)')
    foreign_keys = []
    for child, body in tables.items():
        for line in body.splitlines():
            fk = re.search(r'\b(\w+)\s+.*?REFERENCES (\w+)\(([^)]+)\)', line)
            if fk:
                foreign_keys.append((child, fk[1], fk[2], fk[3]))
    foreign_keys += re.findall(
        r'ALTER TABLE (\w+) ADD (?:CONSTRAINT \w+ )?FOREIGN KEY\s*\(([^)]+)\)\s+REFERENCES (\w+)\(([^)]+)\)', sql)
    column_names = {}
    for name, body in tables.items():
        column_names[name] = [m[1] for line in body.splitlines()
            if (m := re.match(r'\s*(\w+)\s+([\w]+)(?:\([^)]*\))?', line))
            and m[1] not in {'PRIMARY', 'UNIQUE', 'CHECK', 'FOREIGN', 'CONSTRAINT'}]
    (ROOT / 'schema-summary.json').write_text(json.dumps({
        'tables': column_names, 'foreign_key_count': len(foreign_keys)
    }, indent=2) + '\n')

    def diagram(names, with_fields):
        lines = ['erDiagram']
        included = set(names)
        for name in sorted(included):
            if with_fields:
                lines.append(f'  {name} {{')
                for line in tables[name].splitlines():
                    col = re.match(r'\s*(\w+)\s+([\w]+)(?:\([^)]*\))?', line)
                    if col and col[1] not in {'PRIMARY', 'UNIQUE', 'CHECK', 'FOREIGN', 'CONSTRAINT'}:
                        flags = ' PK' if 'PRIMARY KEY' in line else ''
                        lines.append(f'    {col[2]} {col[1]}{flags}')
                lines.append('  }')
        for child, cols, parent, refs in foreign_keys:
            if child in included and parent in included:
                body = tables[child]
                columns = [c.strip() for c in cols.split(',')]
                unique_keys = [set(c.strip() for c in m.split(',')) for m in re.findall(r'(?:PRIMARY KEY|UNIQUE)\s*\(([^)]+)\)', body)]
                inline_keys = re.findall(r'^\s*(\w+) [^\n]*(?:PRIMARY KEY|UNIQUE)', body, re.M)
                unique_keys += [{c} for c in inline_keys]
                primary = re.search(r'PRIMARY KEY\s*\(([^)]+)\)',body)
                primary_cols = set(c.strip() for c in primary[1].split(',')) if primary else set()
                nullable = any(c not in primary_cols and not re.search(r'^\s*'+re.escape(c)+r'\s+[^\n]*(?:NOT NULL|PRIMARY KEY)',body,re.M) for c in columns)
                parent_end = '|o' if nullable else '||'
                child_end = 'o|' if any(key <= set(columns) for key in unique_keys) else 'o{'
                lines.append(f'  {parent} {parent_end}--{child_end} {child} : "{cols.replace(chr(34), "")}"')
        return '\n'.join(lines) + '\n'

    erd = ROOT / 'erd'
    erd.mkdir(exist_ok=True)
    (erd / 'full.mmd').write_text(diagram(tables, True))
    (erd / 'relationships.mmd').write_text(diagram(tables, False))
    module_links = []
    for module, names in MODULES.items():
        selected = names.split()
        (erd / f'{module}.mmd').write_text(diagram(selected, True))
        (erd / f'{module}.md').write_text(f'# ERD — {module}\n\n'+f'```mermaid\n{diagram(selected, True)}```\n')
        module_links.append(f'- [{module}]({module}.md): {len(selected)} tables')
    (erd / 'README.md').write_text('# مخططات ERD المحلية\n\n'
        'تولد من `../schema.sql` عبر `python3 database/build.py`. '\
        'الحقول والعلاقات من SQL مع أعمدة ALTER؛ أطراف العلاقة مشتقة من NULL/PRIMARY KEY/UNIQUE، ولا تستبدل القيود الجزئية أو منطق Trigger في SQL. '\
        'توجد علاقات بين الوحدات في المخطط الكامل.\n\n'
        '- [كامل مع الحقول](full.mmd)\n- [كل العلاقات](relationships.mmd)\n' + '\n'.join(module_links) + '\n')
    dictionary = ['# قاموس قاعدة البيانات المحلي', '',
        f'المخطط المحلي يحتوي {len(tables)} جدولاً. تعريفات الصفوف أدناه من SQL المتولد؛ القيود المضافة بـALTER والـViews والـTriggers في schema.sql.', '',
        'ملفات المصدر الخام تبقى مستقلة في source/. لا يعني توليد القاموس نشر قاعدة إنتاج.', '']
    for module, names in MODULES.items():
        dictionary.extend([f'## {module}', ''])
        for name in names.split():
            dictionary.extend([f'### {name}', '', f'```sql\nCREATE TABLE {name} (\n{tables[name].strip()}\n);\n```', ''])
            relationships = [f'`{cols}` → `{parent}({refs})`' for child, cols, parent, refs in foreign_keys if child == name]
            if relationships:
                dictionary.extend(['المراجع: ' + '؛ '.join(relationships), ''])
    (ROOT / 'data-dictionary.md').write_text('\n'.join(dictionary))
    print(f'Generated schema, 11 Mermaid files and dictionary: {len(tables)} tables, {len(foreign_keys)} FK definitions.')


if __name__ == '__main__':
    build()
